const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);

const clone = value => structuredClone(value);

const same = (left, right) => JSON.stringify(left) === JSON.stringify(right);

const at = (source, path) => path.reduce((value, key) => value?.[key], source);

const pointer = path => `#/${path.map(part => String(part).replace(/~/g, '~0').replace(/\//g, '~1')).join('/')}`;

const pathText = value => Array.isArray(value) ? value.join('.') : '';

const pathParts = (value, label) => {
  if (typeof value !== 'string') throw new Error(`${label} must be a path.`);
  const text = value.trim();
  if (!text) return [];
  const parts = text.split('.').map(part => part.trim());
  if (parts.some(part => !part)) throw new Error(`${label} has an empty path segment.`);
  return parts;
};

const setString = (object, key, value) => {
  if (value.trim()) object[key] = value.trim(); else delete object[key];
};

const setPath = (object, key, value, label) => {
  const parts = pathParts(value, label);
  if (parts.length) object[key] = parts; else delete object[key];
};

export function schemaWithBulkEditActions(document, edits, generatedOwnerAtPath = null) {
  if (!isObject(document) || !Array.isArray(edits) || !edits.length)
    throw new Error('Edit at least one collection action before previewing.');
  const candidate = clone(document), touched = new Set();
  for (const entry of edits) {
    const path = entry?.path;
    if (!Array.isArray(path) || !isObject(at(document, path)))
      throw new Error('A collection declaration changed since this table opened.');
    const identity = pointer(path);
    if (touched.has(identity)) throw new Error(`${identity} was edited twice.`);
    touched.add(identity);
    if (generatedOwnerAtPath?.(document, path)
      || generatedOwnerAtPath?.(document, [...path, 'x-fullmeta-edit']))
      throw new Error(`${identity} is generated by a guided structure input.`);
    const source = at(document, path), next = at(candidate, path);
    if (!Object.hasOwn(entry, 'move') && !Object.hasOwn(entry, 'onInsert'))
      throw new Error(`${identity} has no action changes.`);
    const edit = isObject(source['x-fullmeta-edit']) ? clone(source['x-fullmeta-edit']) : {};
    if (Object.hasOwn(entry, 'move')) {
      if (entry.move === null) delete edit.move;
      else if (isObject(entry.move)) edit.move = clone(entry.move);
      else throw new Error(`${identity}: Move action must be a record.`);
    }
    if (Object.hasOwn(entry, 'onInsert')) {
      if (!Array.isArray(entry.onInsert) || entry.onInsert.some(rule => !isObject(rule)))
        throw new Error(`${identity}: Insert actions must be rows.`);
      if (entry.onInsert.length) edit.onInsert = clone(entry.onInsert);
      else delete edit.onInsert;
    }
    if (Object.keys(edit).length) next['x-fullmeta-edit'] = edit;
    else delete next['x-fullmeta-edit'];
  }
  return candidate;
}

