/** Application-neutral, typed authoring for definitions in any nested $defs owner. */
import { contractFromFlatRows, flatContractRows } from './schema-root-contract-flat.js';

const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const clone = value => structuredClone(value);
const at = (value, path) => path.reduce((node, part) => node?.[part], value);
const pointer = path => `#/${path.map(part => String(part).replace(/~/g, '~0').replace(/\//g, '~1')).join('/')}`;





const valueTypes = [
  ['string', 'Text'], ['escaped-string', 'Escaped text'], ['reference', 'Reference'], ['number', 'Number'],
  ['boolean', 'True / false'], ['null', 'Null'], ['object', 'Object'], ['array', 'Array'],
];
const shapes = [
  ['schema', 'Schema object'], ['object', 'Object declaration'], ['string', 'Text declaration'],
  ['number', 'Number declaration'], ['integer', 'Integer declaration'],
  ['boolean', 'Boolean declaration'], ['null', 'Null declaration'],
  ['array', 'Array declaration'], ['union', 'Union declaration'],
  ['false', 'Always invalid'], ['true', 'Always valid'],
];
const shapeRows = shape => {
  if (['object', 'string', 'number', 'integer', 'boolean', 'null', 'array'].includes(shape)) {
    const rows = [{ path: 'type', type: 'string', value: shape }];
    if (shape === 'object') rows.push({ path: 'properties', type: 'object', value: '' });
    if (shape === 'array') rows.push({ path: 'items', type: 'object', value: '' });
    return rows;
  }
  if (shape === 'union') return [{ path: 'oneOf', type: 'array', value: '' }];
  return [];
};
const shapeOf = value => {
  if (value === false) return 'false';
  if (value === true) return 'true';
  if (isObject(value) && Array.isArray(value.oneOf)) return 'union';
  if (isObject(value) && shapes.some(([key]) => key === value.type)) return value.type;
  return 'schema';
};

/** Discover $defs containers, including namespaced profile collections. */
function definitionOwners(document) {
  const result = [], seen = new Set();
  const schemaKeys = new Set(['$defs', '$ref', 'type', 'properties', 'patternProperties',
    'items', 'additionalProperties', 'oneOf', 'anyOf', 'allOf', 'if', 'then', 'else',
    'not', 'const', 'enum', 'required', 'title', 'description']);
  const visit = (node, path, depth = 0, definitionValue = false) => {
    if (!isObject(node) || depth > 24 || seen.has(node)) return;
    seen.add(node);
    if (isObject(node.$defs)) result.push({ path, keys: Object.keys(node.$defs) });
    for (const [name, child] of Object.entries(node.$defs || {}))
      visit(child, [...path, '$defs', name], depth + 1, true);
    for (const key of ['properties', 'patternProperties'])
      for (const [name, child] of Object.entries(node[key] || {}))
        visit(child, [...path, key, name], depth + 1);
    for (const key of ['items', 'additionalProperties'])
      if (isObject(node[key])) visit(node[key], [...path, key], depth + 1);
    for (const key of ['oneOf', 'anyOf', 'allOf'])
      if (Array.isArray(node[key])) node[key].forEach((child, index) =>
        visit(child, [...path, key, index], depth + 1));
    const namespaceEntries = Object.entries(node).filter(([key]) =>
      !['title', 'description', '$comment'].includes(key) && !key.startsWith('x-'));
    if (definitionValue && namespaceEntries.length && namespaceEntries.every(([key, value]) =>
      !schemaKeys.has(key) && isObject(value))) {
      for (const [name, child] of namespaceEntries)
        visit(child, [...path, name], depth + 1, true);
    }
  };
  visit(document, []);
  return result;
}

/** Replace only explicitly edited definitions, preserving all other declarations. */
export function schemaWithLocalDefinitions(document, edits, generatedOwnerAtPath = null) {
  if (!isObject(document) || !Array.isArray(edits) || !edits.length)
    throw new Error('Add or load at least one definition before previewing.');
  const next = clone(document), edited = new Set();
  for (const [index, edit] of edits.entries()) {
    const ownerPath = edit.ownerPath, key = edit.key?.trim();
    if (!Array.isArray(ownerPath) || !isObject(at(next, ownerPath)?.$defs)
      || !/^[A-Za-z_][A-Za-z0-9_-]*$/.test(key || ''))
      throw new Error(`Definition ${index + 1} needs an owner and a valid key.`);
    const path = [...ownerPath, '$defs', key], name = pointer(path);
    if (edited.has(name)) throw new Error(`${name} is edited twice in this batch.`);
    edited.add(name);
    if (generatedOwnerAtPath?.(document, path))
      throw new Error(`${name} is generated by another guided input.`);
    const prior = at(document, path);
    if (edit.existing && prior === undefined)
      throw new Error(`${name} no longer exists. Reopen the form.`);
    if (!edit.existing && prior !== undefined)
      throw new Error(`${name} already exists. Load it for editing or choose a new key.`);
    let definition;
    if (edit.shape === 'false' || edit.shape === 'true') {
      definition = edit.shape === 'true';
    } else {
      if (!shapes.some(([shape]) => shape === edit.shape))
        throw new Error(`${name} needs a schema declaration shape.`);
      if (!Array.isArray(edit.rows)) throw new Error(`${name} needs typed field rows.`);
      definition = contractFromFlatRows('object', edit.rows);
    }
    at(next, ownerPath).$defs[key] = definition;
  }
  return next;
}

