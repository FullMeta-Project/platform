export function insertionEffectDraft(rule = {}) {
  const base = clone(rule);
  return { base, dirty: [], values: {
    operation: typeof rule.operation === 'string' ? rule.operation : '', scope: typeof rule.scope === 'string' ? rule.scope : '',
    targetPath: pathText(rule.targetPath), valuePath: pathText(rule.valuePath),
    create: typeof rule.create === 'boolean' ? String(rule.create) : '',
    requireValidReference: typeof rule.requireValidReference === 'string' ? rule.requireValidReference : '',
    relatedPath: pathText(rule.related?.path), relatedScope: typeof rule.related?.scope === 'string' ? rule.related.scope : '',
  }, matchesChanged: false, matches: (Array.isArray(rule.related?.matches) ? rule.related.matches : []).map(match => ({ base: clone(match), dirty: [], path: pathText(match.path), equalsTargetParent: pathText(match.equalsTargetParent) })) };
}
export function insertionEffectFromDraft(draft, label = 'Insertion effect', validate = true) {
  const value = clone(draft.base), dirty = new Set(draft.dirty), controls = draft.values;
  for (const key of ['operation', 'scope', 'requireValidReference']) if (dirty.has(key)) setString(value, key, controls[key]);
  for (const key of ['targetPath', 'valuePath']) if (dirty.has(key)) setPath(value, key, controls[key], `${label} ${key}`);
  if (dirty.has('create')) { if (controls.create) value.create = controls.create === 'true'; else delete value.create; }
  if (dirty.has('relatedPath') || dirty.has('relatedScope') || draft.matchesChanged || draft.matches.some(match => match.dirty.length)) {
    const related = isObject(value.related) ? clone(value.related) : {};
    if (dirty.has('relatedPath')) setPath(related, 'path', controls.relatedPath, `${label} related path`);
    if (dirty.has('relatedScope')) setString(related, 'scope', controls.relatedScope);
    if (draft.matchesChanged || draft.matches.some(match => match.dirty.length)) {
      const matches = draft.matches.map((match, index) => {
        const result = clone(match.base);
        if (match.dirty.includes('path')) setPath(result, 'path', match.path, `${label} match ${index + 1} path`);
        if (match.dirty.includes('equalsTargetParent')) setPath(result, 'equalsTargetParent', match.equalsTargetParent, `${label} match ${index + 1} target parent path`);
        if (validate && (!Array.isArray(result.path) || !Array.isArray(result.equalsTargetParent))) throw new Error(`${label} match ${index + 1} needs both paths.`);
        return result;
      });
      if (matches.length) related.matches = matches; else delete related.matches;
    }
    if (Object.keys(related).length) value.related = related; else delete value.related;
  }
  if (validate && (!value.operation || !Array.isArray(value.targetPath) || !value.targetPath.length || !Array.isArray(value.valuePath) || !value.valuePath.length)) throw new Error(`${label} needs an operation, target path, and value path.`);
  return value;
}
export function insertionEffectsFromTsv(text) {
  const lines = text.split(/\r?\n/).filter(line => line.trim());
  const first = lines[0]?.split('\t').map(value => value.trim().toLowerCase());
  if (first?.length >= 4 && ['operation', 'action'].includes(first[0]) && first[1] === 'scope' && ['target path', 'targetpath'].includes(first[2]) && ['value path', 'valuepath'].includes(first[3])) lines.shift();
  if (!lines.length) throw new Error('Paste at least one tab-separated insertion effect row.');
  return lines.map((line, index) => {
    const columns = line.split('\t');
    if (columns.length < 4 || columns.length > 6) throw new Error(`Row ${index + 1} needs 4 to 6 tab-separated columns.`);
    const [operation, scope, targetPath, valuePath, create, reference] = columns, rule = {};
    setString(rule, 'operation', operation); setString(rule, 'scope', scope);
    setPath(rule, 'targetPath', targetPath, `Row ${index + 1} target path`); setPath(rule, 'valuePath', valuePath, `Row ${index + 1} value path`);
    if (!rule.operation || !rule.targetPath?.length || !rule.valuePath?.length) throw new Error(`Row ${index + 1} needs an operation, target path, and value path.`);
    if (create?.trim()) { if (!['true', 'false'].includes(create.trim().toLowerCase())) throw new Error(`Row ${index + 1} create target must be true or false.`); rule.create = create.trim().toLowerCase() === 'true'; }
    setString(rule, 'requireValidReference', reference || ''); return rule;
  });
}
