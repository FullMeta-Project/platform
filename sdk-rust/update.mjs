// Generate low-level Rust DLL bindings from the platform's public C headers.
// Higher-level safe wrappers and JSON operation contracts are not generated.
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args=new Set(process.argv.slice(2));
for (const arg of args) if (arg!=='--check') throw Error(`Unknown option: ${arg}`);
const components=[
  ['core','core-rust/core-native.h','core-rust/lib/fullmeta_core.dll'],
  ['model','model-rust/model-native.h','model-rust/lib/fullmeta_model.dll'],
  ['contracts','operation-contracts-rust/contracts-native.h','operation-contracts-rust/lib/fullmeta_operation_contracts.dll'],
];
const sdkDirectory={core:'core',model:'model',contracts:'operation-contracts'};
const primitives={void:'std::ffi::c_void',uint8_t:'u8',int8_t:'i8',uint16_t:'u16',int16_t:'i16',uint32_t:'u32',int32_t:'i32',uint64_t:'u64',int64_t:'i64',size_t:'usize',double:'f64',float:'f32'};
function typeOf(c, known, returning=false) {
  const parts=c.trim().replace(/\s+/g,' ').split('*').map(part=>part.trim());
  const base=parts[0].replace(/\bconst\b/g,'').trim();
  if (!(base in primitives) && !known.has(base)) throw Error(`Unsupported C type: ${c}`);
  if (parts.slice(1).some(part=>part && part!=='const')) throw Error(`Unsupported pointer qualifier: ${c}`);
  if (base==='void' && parts.length===1 && returning) return '()';
  if (base==='void' && parts.length===1) throw Error(`Unexpected void: ${c}`);
  let result=primitives[base]||base;
  for(let i=1;i<parts.length;i++) result=`*${/\bconst\b/.test(parts[i-1])?'const':'mut'} ${result}`;
  return result;
}
function argumentsOf(source, known) {
  if (!source.trim() || source.trim()==='void') return [];
  return source.split(',').map(arg=>{
    const match=arg.trim().match(/^(.+?)([A-Za-z_][A-Za-z0-9_]*)$/);
    if(!match) throw Error(`Unsupported argument: ${arg}`);
    return [match[2],typeOf(match[1],known)];
  });
}
function parseHeader(header, prefix) {
  let src=header.replace(/\/\*[\s\S]*?\*\//g,'').replace(/\/\/[^\n]*/g,'')
    .replace(/^\s*#.*$/gm,'').replace(/extern\s+"C"\s*\{/g,'').replace(/^\s*}\s*$/gm,'');
  const known=new Set(), structures=[], callbacks=[], functions=[];
  src=src.replace(/typedef\s+struct\s*\{([\s\S]*?)\}\s*([A-Za-z_]\w*)\s*;/g,(_,body,name)=>{
    known.add(name); structures.push({name,body}); return '';
  });
  src=src.replace(/typedef\s+([^;()]+?)\s*\(\s*\*\s*([A-Za-z_]\w*)\s*\)\s*\(([^;()]*)\)\s*;/g,(_,ret,name,args)=>{
    known.add(name); callbacks.push({name,ret,args}); return '';
  });
  const proto=new RegExp(`([^;{}]+?)\\b(${prefix}_[A-Za-z0-9_]+)\\s*\\(([^;{}()]*)\\)\\s*;`,'g');
  src=src.replace(proto,(_,ret,name,args)=>{functions.push({name,ret,args});return '';});
  if(src.trim()) throw Error(`Unrecognized declaration in ${prefix} header: ${src.trim().slice(0,200)}`);
  if(!functions.length) throw Error(`No ${prefix} declarations found`);
  if(new Set(functions.map(x=>x.name)).size!==functions.length) throw Error(`Duplicate ${prefix} declaration`);
  const lines=['// @generated by platform/sdk-rust/update.mjs. Do not edit.',
    '//! Low-level DLL bindings. See the platform C header for ownership, threading and safety rules.',
    '#![allow(non_camel_case_types)]',''];
  for(const {name,body} of structures){
    lines.push('#[repr(C)]','#[derive(Clone, Copy, Debug)]',`pub struct ${name} {`);
    for(const field of body.split(';').map(x=>x.trim()).filter(Boolean)){
      const match=field.match(/^(.+?)\s+([A-Za-z_]\w*)(?:\[(\d+)\])?$/);
      if(!match) throw Error(`Unsupported ${name} field: ${field}`);
      const t=typeOf(match[1],known); lines.push(`    pub ${match[2]}: ${match[3]?`[${t}; ${match[3]}]`:t},`);
    }
    lines.push('}','');
  }
  for(const {name,ret,args} of callbacks){
    const inputs=argumentsOf(args,known).map(([n,t])=>`${n}: ${t}`).join(', ');
    lines.push(`pub type ${name} = Option<unsafe extern "C" fn(${inputs}) -> ${typeOf(ret,known,true)}>;`,'');
  }
  for(const {name,ret,args} of functions){
    const inputs=argumentsOf(args,known).map(([n,t])=>`${n}: ${t}`).join(', ');
    lines.push(`pub type ${name}_fn = unsafe extern "C" fn(${inputs}) -> ${typeOf(ret,known,true)};`);
  }
  lines.push('','/// Function pointers for one loaded DLL. The caller owns the library lifetime.','pub struct NativeApi {');
  for(const {name} of functions) lines.push(`    pub ${name}: ${name}_fn,`);
  lines.push('}','', 'impl NativeApi {',
    '    /// Resolve the declarations from the matching loaded DLL.',
    '    ///', '    /// # Safety',
    '    /// The resolver must return the named function with exactly the declared ABI.',
    '    /// Keep the DLL loaded while any resolved function pointer is used.',
    '    pub unsafe fn load(mut resolve: impl FnMut(&str) -> Result<*const std::ffi::c_void, String>) -> Result<Self, String> {',
    '        Ok(Self {');
  for(const {name} of functions){
    lines.push(`            ${name}: { let pointer = resolve("${name}")?;`,
      `                if pointer.is_null() { return Err("Missing DLL symbol ${name}".into()); }`,
      `                unsafe { std::mem::transmute::<*const std::ffi::c_void, ${name}_fn>(pointer) } },`);
  }
  lines.push('        })','    }','}','');
  return {code:lines.join('\n'),names:functions.map(x=>x.name).sort()};
}
function exportsOf(path,prefix){
  const result=spawnSync(process.env.OBJDUMP||'objdump',['-p',path],{encoding:'utf8',windowsHide:true,maxBuffer:32*1024*1024});
  if(result.error || result.status!==0) throw Error(`Cannot inspect ${path} with objdump: ${result.error||result.stderr}`);
  const match=result.stdout.match(/\[Ordinal\/Name Pointer\] Table\s*\r?\n([\s\S]*?)(?:\r?\n\s*\r?\n|$)/);
  if(!match) throw Error(`Cannot find exports in ${path}`);
  return [...match[1].matchAll(/^\s*\[\s*\d+\]\s+(\S+)\s*$/gm)].map(m=>m[1]).filter(n=>n.startsWith(`${prefix}_`)).sort();
}
const outputs=[];
for(const [name,header,dll] of components){
  const {code,names}=parseHeader(readFileSync(resolve(root,header),'utf8'),name);
  const actual=exportsOf(resolve(root,dll),name);
  const missing=actual.filter(n=>!names.includes(n)), stale=names.filter(n=>!actual.includes(n));
  if(missing.length||stale.length) throw Error(`${name} header and DLL exports differ. Undeclared exports: ${missing.join(', ')||'none'}; missing exports: ${stale.join(', ')||'none'}`);
  const output=resolve(root,'sdk-rust',sdkDirectory[name],'src/native.rs');
  const previous=existsSync(output)?readFileSync(output,'utf8'):null;
  if(args.has('--check') && previous!==code) throw Error(`${output} is out of date; run node platform/sdk-rust/update.mjs`);
  outputs.push({name,output,code,previous,count:names.length});
}
for(const {name,output,code,previous,count} of outputs){
  if(!args.has('--check') && previous!==code){
    writeFileSync(output,code);
    if(previous!==null) console.warn(`${name}: native bindings changed; review higher-level SDK wrappers and ABI compatibility.`);
  }
  console.log(`${name}: ${count} native declarations ${args.has('--check')?'verified':'generated'}; DLL exports match`);
}
