/** Application-neutral root composition and conditional schema authoring. */
const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const clone = value => structuredClone(value);
const at = (source, path) => path.reduce((value, key) => value?.[key], source);





const pointer = parts => `#/${parts.map(part => String(part).replace(/~/g, '~0').replace(/\//g, '~1')).join('/')}`;
const pathText = path => Array.isArray(path) ? path.every(part => typeof part === 'string' && !part.includes('.'))
  ? path.join('.') : `/${path.map(part => String(part).replace(/~/g, '~0').replace(/\//g, '~1')).join('/')}` : '';
const pathParts = (text, label) => {
  const value = text.trim();
  if (!value) throw new Error(`${label} needs a property path.`);
  const parts = value.startsWith('/')
    ? value.slice(1).split('/').map(part => part.replace(/~1/g, '/').replace(/~0/g, '~'))
    : value.split('.').map(part => part.trim());
  if (parts.some(part => !part)) throw new Error(`${label} has an empty path segment.`);
  return parts;
};
const referenceParts = ref => {
  if (typeof ref !== 'string' || !ref.startsWith('#/')) return null;
  return ref.slice(2).split('/').map(part => part.replace(/~1/g, '/').replace(/~0/g, '~'));
};
const referenceExists = (document, ref) => {
  const parts = referenceParts(ref);
  return !!parts && at(document, parts) !== undefined;
};
const schemaForConst = (path, value) => {
  let node = { const: value };
  for (const part of [...path].reverse()) node = { properties: { [part]: node } };
  return node;
};
const simpleConstChain = value => {
  const path = []; let node = value;
  while (isObject(node) && Object.keys(node).length === 1 && isObject(node.properties)
    && Object.keys(node.properties).length === 1) {
    const [key] = Object.keys(node.properties); path.push(key); node = node.properties[key];
  }
  return path.length && isObject(node) && Object.keys(node).length === 1
    && Object.hasOwn(node, 'const') && (node.const === null
      || ['string', 'number', 'boolean'].includes(typeof node.const))
    ? { path, value: node.const } : null;
};
const valueKind = value => value === null ? 'null' : typeof value;
const readConst = (kind, text, label) => {
  if (kind === 'null') return null;
  if (kind === 'boolean') {
    if (!['true', 'false'].includes(text.trim())) throw new Error(`${label} must be true or false.`);
    return text.trim() === 'true';
  }
  if (kind === 'number') {
    if (!text.trim() || !Number.isFinite(Number(text))) throw new Error(`${label} must be a finite number.`);
    return Number(text);
  }
  if (kind === 'string') return text;
  throw new Error(`${label} has an unknown value type.`);
};

/** Replace only the edited root composition keywords, preserving every other root key. */
export function schemaWithRootConstraints(document, changes, generatedOwnerAtPath = null) {
  if (!isObject(document) || !isObject(changes) || !Object.keys(changes).length)
    throw new Error('Edit at least one root constraint before previewing.');
  const next = clone(document);
  if (Object.hasOwn(changes, 'allOf')) {
    if (generatedOwnerAtPath?.(document, ['allOf']))
      throw new Error('Root composition is generated by another guided input.');
    if (!Array.isArray(changes.allOf) || changes.allOf.some(entry => !isObject(entry)))
      throw new Error('Composition rows must be schema declarations.');
    for (const [index, entry] of changes.allOf.entries()) {
      if (Object.keys(entry).length === 1 && typeof entry.$ref === 'string'
        && !referenceExists(next, entry.$ref))
        throw new Error(`Composition row ${index + 1} must point to an existing local definition.`);
    }
    if (changes.allOf.length) next.allOf = clone(changes.allOf);
    else delete next.allOf;
  }
  if (Object.hasOwn(changes, 'condition')) {
    for (const key of ['if', 'then', 'else'])
      if (generatedOwnerAtPath?.(document, [key]))
        throw new Error(`Root ${key} is generated by another guided input.`);
    if (changes.condition === null) {
      delete next.if; delete next.then; delete next.else;
    } else {
      const condition = changes.condition;
      if (!isObject(condition) || !Array.isArray(condition.when?.path)
        || !Array.isArray(condition.then?.path))
        throw new Error('Root condition needs When and Then property rows.');
      next.if = schemaForConst(condition.when.path, condition.when.value);
      next.then = schemaForConst(condition.then.path, condition.then.value);
      if (condition.otherwise) {
        if (!Array.isArray(condition.otherwise.path))
          throw new Error('Otherwise needs a property path.');
        next.else = schemaForConst(condition.otherwise.path, condition.otherwise.value);
      } else delete next.else;
    }
  }
  return next;
}


function definitionRefs(document) {
    const result = [];
    const schemaKeys = new Set(['$defs', '$ref', 'type', 'properties', 'patternProperties',
      'items', 'additionalProperties', 'oneOf', 'anyOf', 'allOf', 'if', 'then', 'else',
      'not', 'const', 'enum', 'required', 'title', 'description']);
    const visit = (node, path, depth = 0, definitionValue = false) => {
      if (!isObject(node) || depth > 20) return;
      for (const [key, value] of Object.entries(node.$defs || {})) {
        const next = [...path, '$defs', key];
        result.push(pointer(next)); visit(value, next, depth + 1, true);
      }
      const namespaceEntries = Object.entries(node).filter(([key]) =>
        !['title', 'description', '$comment'].includes(key) && !key.startsWith('x-'));
      if (definitionValue && namespaceEntries.length && namespaceEntries.every(([key, value]) =>
        !schemaKeys.has(key) && isObject(value))) {
        for (const [key, value] of namespaceEntries)
          visit(value, [...path, key], depth + 1, true);
      }
    };
    visit(document, []);
    return result;
  }

