import { inspectSchemaStructure } from './schema-structure-inspector.js';
import { schemaGeneratedOwnershipIssue } from './schema-structure-authoring.js';
import { validateSchemaValueDeclarationCompatibility } from './schema-value-control-authoring.js';
import { validateSchemaFragment } from "../../../model-rust/js/api.js";

const isRecord = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const samePath = (left, right) => left.length === right.length && left.every((part, index) => part === right[index]);
const prefixOf = (prefix, path) => prefix.length <= path.length && prefix.every((part, index) => part === path[index]);
const pointer = path => `/${path.map(part => String(part).replace(/~/g, '~0').replace(/\//g, '~1')).join('/')}`;
const atPath = (document, path) => path.reduce((value, part) => value?.[part], document);
const allowedColumns = new Set(['title', 'required', 'widget', 'hidden', 'defaultValue', 'choices', 'referencePath', 'referenceLabel']);
const standardWidgets = new Set(['', 'valueControl', 'referenceSelector', 'quantity', 'quantityVector', 'tree']);

function generatedOwner(document, path) {
  return (document?.['x-fullmeta-ui-generated']?.fields || [])
    .find(entry => Array.isArray(entry?.path) && prefixOf(entry.path, path))?.owner || null;
}

function mutationPath(fieldPath, column) {
  if (column === 'required') return [...fieldPath.slice(0, -2), 'required'];
  if (column === 'widget') return [...fieldPath, 'x-fullmeta-ui-behavior', 'payload', 'widget'];
  if (column === 'hidden') return [...fieldPath, 'x-fullmeta-ui-behavior', 'payload', 'presentation', 'hidden'];
  if (column === 'defaultValue') return [...fieldPath, 'default'];
  if (column === 'choices') return [...fieldPath, 'enum'];
  if (column === 'referencePath') return [...fieldPath, 'x-fullmeta-modelReference', 'targetPath'];
  if (column === 'referenceLabel') return [...fieldPath, 'x-fullmeta-modelReference', 'targetLabel'];
  return [...fieldPath, column];
}

/** Explain why a reverse-table cell cannot safely round trip. */
export function structureCellEditIssue(document, row, column, { allowGeneratedTableEdit = false } = {}) {
  if (!allowedColumns.has(column)) return 'This column describes schema shape; use a guided structure operation to change it.';
  const fieldPath = row?.path;
  if (!Array.isArray(fieldPath) || fieldPath.at(-2) !== 'properties') return 'This is not a direct property declaration.';
  const field = atPath(document, fieldPath);
  if (!isRecord(field)) return 'This property declaration is not an object.';
  if (!allowGeneratedTableEdit) {
    const fieldOwner = generatedOwner(document, fieldPath);
    if (fieldOwner) return `Generated by ${fieldOwner.input}; use an authoring table to change it.`;
    const owner = generatedOwner(document, mutationPath(fieldPath, column));
    if (owner) return `Generated by ${owner.input}; use an authoring table to change it.`;
  }
  if (column === 'widget' || column === 'hidden') {
    const behavior = field['x-fullmeta-ui-behavior'];
    if (behavior !== undefined && (!isRecord(behavior) || behavior.format !== 'fullmeta-ui-behavior/1'
      || behavior.target?.kind !== 'field' || !isRecord(behavior.payload))) {
      return 'Custom UI behavior; use the field annotation editor.';
    }
    if (column === 'widget' && !standardWidgets.has(behavior?.payload?.widget?.type || '')) {
      return 'Custom widget; use the field annotation editor.';
    }
    if (column === 'widget' && Object.keys(behavior?.payload?.widget?.settings || {}).length) {
      return 'This widget has settings that need its dedicated field annotation editor.';
    }
  }
  if ((column === 'defaultValue' || column === 'choices')
    && ['oneOf', 'anyOf', 'allOf', 'if', 'then', 'else', 'not'].some(key => Object.hasOwn(field, key))) {
    return 'Conditional or combined schema; edit its value rules in the field editor.';
  }
  if (column === 'defaultValue' && Object.hasOwn(field, 'const')) {
    return 'This field has a fixed value; edit the fixed declaration through its owning control.';
  }
  if (column === 'choices' && Object.hasOwn(field, 'const')) {
    return 'This field has a fixed value; edit the fixed declaration through its owning control.';
  }
  if (column === 'referencePath' || column === 'referenceLabel') {
    const source = field['x-fullmeta-modelReference'];
    if (!isRecord(source)) return 'Add a reference source in the field annotation editor first.';
    if (column === 'referencePath' && (!Array.isArray(source.targetPath)
      || source.targetPath.some(part => typeof part !== 'string' || !part || part.includes('.')))) {
      return 'This reference path has a custom shape; use the field annotation editor.';
    }
    if (column === 'referenceLabel' && typeof source.targetLabel !== 'string') {
      return 'This reference label has a custom shape; use the field annotation editor.';
    }
  }
  return '';
}

function ensureBehavior(field) {
  field['x-fullmeta-ui-behavior'] ||= {
    format: 'fullmeta-ui-behavior/1', target: { kind: 'field' },
    context: 'projectEditing', payload: {},
  };
  return field['x-fullmeta-ui-behavior'].payload;
}

function applyOne(document, edit) {
  const field = atPath(document, edit.path);
  const parent = atPath(document, edit.path.slice(0, -2));
  const key = edit.path.at(-1);
  switch (edit.column) {
    case 'title':
      if (typeof edit.value !== 'string') throw new Error('Title must be text.');
      if (edit.value.trim()) field.title = edit.value.trim();
      else delete field.title;
      break;
    case 'required': {
      if (typeof edit.value !== 'boolean') throw new Error('Required must be a checkbox value.');
      const required = new Set(Array.isArray(parent.required) ? parent.required : []);
      if (edit.value) required.add(key); else required.delete(key);
      parent.required = [...required];
      break;
    }
    case 'widget': {
      if (typeof edit.value !== 'string' || !standardWidgets.has(edit.value)) throw new Error('Choose a supported widget.');
      if (edit.value) {
        const payload = ensureBehavior(field);
        payload.widget ||= { type: edit.value, settings: {} };
        payload.widget.type = edit.value;
      } else if (field['x-fullmeta-ui-behavior']?.payload?.widget) {
        delete field['x-fullmeta-ui-behavior'].payload.widget;
      }
      break;
    }
    case 'hidden': {
      if (typeof edit.value !== 'boolean') throw new Error('Hidden must be a checkbox value.');
      if (edit.value) {
        const payload = ensureBehavior(field);
        payload.presentation ||= {};
        payload.presentation.hidden = true;
      } else if (field['x-fullmeta-ui-behavior']?.payload?.presentation) {
        delete field['x-fullmeta-ui-behavior'].payload.presentation.hidden;
      }
      break;
    }
    case 'defaultValue':
      if (edit.remove) delete field.default;
      else {
        if (edit.value === undefined) throw new Error('Enter a JSON default or clear the cell to remove it.');
        field.default = structuredClone(edit.value);
      }
      break;
    case 'choices':
      if (edit.remove) delete field.enum;
      else {
        if (!Array.isArray(edit.value) || !edit.value.length) throw new Error('Choices must be a nonempty JSON array.');
        field.enum = structuredClone(edit.value);
      }
      break;
    case 'referencePath':
      if (!Array.isArray(edit.value) || !edit.value.length
        || edit.value.some(part => typeof part !== 'string' || !(part === '*' || /^[A-Za-z_][A-Za-z0-9_\-]*$/.test(part))
          || ['__proto__', 'constructor', 'prototype'].includes(part))) {
        throw new Error('Reference target path needs dotted property names.');
      }
      field['x-fullmeta-modelReference'].targetPath = [...edit.value];
      break;
    case 'referenceLabel':
      if (typeof edit.value !== 'string' || !edit.value.trim()) throw new Error('Reference target label cannot be empty.');
      field['x-fullmeta-modelReference'].targetLabel = edit.value.trim();
      break;
    default: throw new Error(`The ${edit.column} column cannot be edited here.`);
  }
}

/** Apply only explicitly edited cells, retaining every other keyword and ownership entry. */
export function schemaWithEditedStructureFields(document, selectedPath, edits) {
  if (!isRecord(document) || !Array.isArray(selectedPath) || !Array.isArray(edits) || !edits.length) {
    throw new Error('Change at least one editable table cell before previewing.');
  }
  const selected = atPath(document, selectedPath);
  if (!isRecord(selected)) throw new Error('Select an object or array schema declaration.');
  const allowed = new Set(inspectSchemaStructure(document, selectedPath)
    .flatMap(section => section.rows.map(row => JSON.stringify(row.path))));
  const next = structuredClone(document), seen = new Set(), touched = new Map(), valueEdits = new Set();
  for (const edit of edits) {
    if (!isRecord(edit) || !Array.isArray(edit.path) || !allowedColumns.has(edit.column)
      || !allowed.has(JSON.stringify(edit.path))) throw new Error('A table edit no longer belongs to the selected structure. Reopen it.');
    const row = { path: edit.path };
    const issue = structureCellEditIssue(document, row, edit.column, { allowGeneratedTableEdit: true });
    if (issue) throw new Error(`${edit.path.at(-1)} ${edit.column}: ${issue}`);
    const identity = JSON.stringify([edit.path, edit.column]);
    if (seen.has(identity)) throw new Error('The same table cell was edited twice.');
    seen.add(identity);
    touched.set(JSON.stringify(edit.path), edit.path);
    if (edit.column === 'defaultValue' || edit.column === 'choices') valueEdits.add(JSON.stringify(edit.path));
    applyOne(next, edit);
  }
  for (const path of touched.values()) {
    const nextField = atPath(next, path);
    validateSchemaValueDeclarationCompatibility(atPath(document, path), nextField);
    if (valueEdits.has(JSON.stringify(path))) {
      if (Object.hasOwn(nextField, 'default')) {
        const errors = validateSchemaFragment(nextField.default, nextField, next);
        if (errors.length) throw new Error(`${path.at(-1)} default: ${errors[0]}`);
      }
      if (Array.isArray(nextField.enum)) {
        const unrestricted = { ...nextField }; delete unrestricted.enum;
        for (const choice of nextField.enum) {
          const errors = validateSchemaFragment(choice, unrestricted, next);
          if (errors.length) throw new Error(`${path.at(-1)} choices: ${errors[0]}`);
        }
      }
    }
  }
  const ownershipIssue = schemaGeneratedOwnershipIssue(document, next, {
    allowGeneratedPaths: edits.map(edit => mutationPath(edit.path, edit.column)),
  });
  if (ownershipIssue) throw new Error(ownershipIssue);
  return {
    document: next, path: selectedPath, label: selected.title || 'schema structure',
    changedPaths: [...touched.values()].map(pointer),
  };
}
